#!/usr/bin/env python3
"""Generate paper table fragments from provenance-authorized JSON fields."""
from __future__ import annotations
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "mecc_package" / "results" / "raw" / "mixtral_real.json"
TARGET = ROOT / "mecc_package" / "paper" / "generated_mixtral_table.tex"

def render(data):
    ours, swap = data["results"]["ours"], data["results"]["swapmoe"]
    return f"""% Generated by scripts/generate_paper_tables.py; do not hand-edit.
\\begin{{table}}[!h]
\\centering
\\caption{{Mixtral-8\\(\\times\\)7B L2端到端结果（{data['platform']}，冷SSD）}}
\\label{{tab:mixtral_e2e}}
\\begin{{tabular}}{{lrrrr}}
\\toprule
策略 & 综合加速 & fp16 PPL & SSD命中 & CPU命中 \\\\
\\midrule
OURS & {ours['speedup_vs']['swapmoe']:.3f}\\(\\times\\) & {ours['ppl']:.2f} & {ours['hit_pct']['ssd']:.1f}\\% & {ours['hit_pct']['cpu']:.1f}\\% \\\\
SwapMoE-style & 1.000\\(\\times\\) & --\\textsuperscript{{*}} & {swap['hit_pct']['ssd']:.1f}\\% & {swap['hit_pct']['cpu']:.1f}\\% \\\\
\\bottomrule
\\end{{tabular}}
\\vspace{{2pt}}\\footnotesize{{\\textsuperscript{{*}}历史JSON对照PPL身份未核实（PROVENANCE X6），不作质量claim。}}
\\end{{table}}
"""

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    expected = render(json.loads(SOURCE.read_text()))
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit("generated paper table is stale")
    else:
        TARGET.write_text(expected)

if __name__ == "__main__": main()
