"""Check the generated scenario manuscript, not research validity."""
from pathlib import Path
import collections
import json
import re
import argparse
import pymupdf

P=Path(__file__).resolve().parent


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--stem',default='mecc_dac2027')
    args=ap.parse_args()
    d=pymupdf.open(P/(args.stem+'.pdf'))
    s=(P/'mecc_dac2027.tex').read_text(encoding='utf-8')
    a=json.loads((P/'ideal_assumptions.json').read_text())
    log=(P/(args.stem+'.log')).read_text(errors='replace')
    texts=[p.get_text() for p in d]
    reference_pages=[i for i,t in enumerate(texts) if t.startswith('References')]
    reference_start=reference_pages[0] if reference_pages else len(d)
    abstract=s.split('\\begin{abstract}')[1].split('\\end{abstract}')[0]
    # Editorial markup must not change the abstract's word-count check.
    abstract=re.sub(r'\\(?:draftnote|draftvalue|ainote)\{([^{}]*)\}',r'\1',abstract)
    count=len(abstract.split())
    bbl=(P/(args.stem+'.bbl')).read_text(encoding='utf-8')
    bibkeys=re.findall(r'\\bibitem\{([^}]+)\}',bbl)
    cited={key.strip() for group in re.findall(r'\\cite\{([^}]+)\}',s) for key in group.split(',')}
    sizes=collections.Counter()
    for p in d:
        for b in p.get_text('dict')['blocks']:
            for line in b.get('lines',[]):
                for sp in line['spans']:
                    sizes[round(sp['size'],2)]+=len(sp['text'])
    checks={
      'at_most_six_body_pages_plus_one_reference_page':reference_start<=6 and len(d)<=7,
      'references_occupy_one_final_page':reference_pages==[len(d)-1],
      'references_page_has_no_body_sections':not any(x in texts[-1] for x in ['Conclusion','Content Generated by AI','VI.','VII.']),
      'ieee_9pt_class':'[conference,9pt,letterpaper]{IEEEtran}' in s,
      '9pt_reported_by_latex':'This is a 9 point document' in log,
      'body_font_is_9pt':abs(sizes.most_common(1)[0][0]-9)<.05,
      'letter_page':all(abs(p.rect.width-612)<.1 and abs(p.rect.height-792)<.1 for p in d),
      'author_metadata_empty':not d.metadata.get('author'),
      'hypothetical_metadata':'hypothetical' in d.metadata.get('subject','').lower(),
      'visible_hypothetical_notice_every_page':all('HYPOTHETICAL RESULTS DESIGN DRAFT' in t for t in texts),
      'ai_disclosure_in_body':any('Content Generated by AI' in t for t in texts[:reference_start]),
      'abstract_about_100_words':90<=count<=110,
      'no_undefined_citations_or_references':'undefined' not in log.lower(),
      'no_overfull_boxes':'Overfull' not in log,
      'single_gpu_speedup_range':all(3<=x/y<=3.3 for x,y in zip(a['tpot_seconds']['Unoptimized streaming'],a['tpot_seconds']['MECC'])),
      'eight_gpu_example_equal_gpu_time':a['tpot_seconds']['MECC'][0]==8*a['tpot_seconds']['Resident 8-GPU reference'][0],
      'placement_comparison_same_slots':sum(a['motivation']['cpu_slots_uniform'])==sum(a['motivation']['cpu_slots_planned']),
      'overlap_only_preserves_demand_misses':a['ablation_ssd_percent'][-1]==a['ablation_ssd_percent'][-2],
      'archived_memory_parts_arithmetic_only':sum(a['memory_gb']['gpu_parts'])<=a['memory_gb']['gpu_cap'] and sum(a['memory_gb']['cpu_parts'])<=a['memory_gb']['cpu_cap'],
      'bibliography_matches_actual_citations':bool(bibkeys) and set(bibkeys)==cited,
      'no_uncited_bibliography_padding':r'\nocite' not in s,
      'yellow_data_and_blue_ai_markers':all(x in s for x in [r'\draftvalue{',r'\draftnote{',r'\ainote{OpenAI']),
    }
    report={'scope':'Format and hypothetical-scenario consistency only; NOT evidence or acceptance certification',
            'pdf_file':args.stem+'.pdf',
            'reference_count':len(bibkeys),
            'checks':checks,'page_count':len(d),'body_pages':reference_start,'abstract_whitespace_words':count,
            'dominant_pdf_font_sizes':sizes.most_common(5),'hypothetical_results':True,
            'ready_for_submission':False,'open_evidence_issues':['PROVENANCE X7','PROVENANCE X8','PROVENANCE X9','All scenario outcomes require real experiments','Archived mirror breakdown is not physically feasible for full mirroring','Planner guards, async readiness, and phase counters need implementation validation']}
    (P/'validation.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps(report,indent=2))
    assert all(checks.values()),'Draft checks failed'


if __name__=='__main__': main()
